/**
 * P9.5 - Verify versioned type generation output structure
 *
 * Ensures that `scripts/generate-types.sh` produced the expected
 * directory layout and file set for each supported BMS version.
 *
 * These tests are structural (file-existence) checks only — they do NOT
 * import or execute the generated types (that would create circular
 * dependencies between the test harness and generated output).
 *
 * See ADR-006-Multi-Version-OpenAPI.md for the versioned type directory design.
 */

import { describe, it, expect } from 'vitest';
import { existsSync, readdirSync } from 'fs';
import { join } from 'path';

const GENERATED_BASE = join(__dirname, '../../../src/generated');

// ──────────────────────────────────────────────────────────────
// Expected output for each BMS version
// ──────────────────────────────────────────────────────────────
const CORE_TYPE_FILES = [
  'active-directory.types.ts',
  'assets.types.ts',
  'defense-control.types.ts',
  'endpoints.types.ts',
  'jobs.types.ts',
  'operating-systems.types.ts',
  'server-management.types.ts',
  'software.types.ts',
  'update-management.types.ts',
  'variables.types.ts',
];

const VERSION_EXPECTATIONS: Record<string, { files: string[]; total: number }> = {
  '25r2': {
    files: CORE_TYPE_FILES,
    total: 10,
  },
  '26r1': {
    files: [
      ...CORE_TYPE_FILES,
      'compliance.types.ts',           // 26R1 new API
      'universaldynamicgroups.types.ts', // 26R1 new API
    ],
    total: 12,
  },
};

// ──────────────────────────────────────────────────────────────
// Tests
// ──────────────────────────────────────────────────────────────
describe('versioned TypeScript type generation (P9.3/P9.4)', () => {
  it('src/generated/ base directory exists', () => {
    expect(existsSync(GENERATED_BASE)).toBe(true);
  });

  for (const [version, expectations] of Object.entries(VERSION_EXPECTATIONS)) {
    describe(`BMS ${version}`, () => {
      const versionDir = join(GENERATED_BASE, version);

      it(`src/generated/${version}/ directory exists`, () => {
        expect(existsSync(versionDir)).toBe(true);
      });

      it(`contains exactly ${expectations.total} type files`, () => {
        const files = readdirSync(versionDir).filter((f) => f.endsWith('.types.ts'));
        expect(files.length).toBe(expectations.total);
      });

      for (const expectedFile of expectations.files) {
        it(`contains ${expectedFile}`, () => {
          expect(existsSync(join(versionDir, expectedFile))).toBe(true);
        });
      }

      it('all files are non-empty TypeScript', () => {
        const { readFileSync } = require('fs');
        const files = readdirSync(versionDir).filter((f) => f.endsWith('.types.ts'));
        for (const file of files) {
          const content = readFileSync(join(versionDir, file), 'utf-8') as string;
          // Generated by openapi-typescript — must contain export declarations
          expect(content.length, `${file} should not be empty`).toBeGreaterThan(100);
          expect(content, `${file} should contain TypeScript exports`).toMatch(/export\s+(type|interface|const)/);
        }
      });

      it('directory name matches BmsVersion enum value (lowercase)', () => {
        // Enum values: BmsVersion.BMS_25R2 = '25r2', BmsVersion.BMS_26R1 = '26r1'
        // Directory names must be lowercase to match enum string values
        expect(version).toMatch(/^[a-z0-9]+$/);
      });
    });
  }

  it('no unexpected version directories exist', () => {
    const knownVersions = Object.keys(VERSION_EXPECTATIONS);
    const actualDirs = readdirSync(GENERATED_BASE, { withFileTypes: true })
      .filter((d) => d.isDirectory())
      .map((d) => d.name);

    for (const dir of actualDirs) {
      expect(
        knownVersions,
        `Unknown version directory '${dir}' found in src/generated/ — add to VERSION_EXPECTATIONS or remove the directory`,
      ).toContain(dir);
    }
  });

  it('generate-types.sh script exists and is valid bash', () => {
    const scriptPath = join(__dirname, '../../../scripts/generate-types.sh');
    expect(existsSync(scriptPath)).toBe(true);
    // Must start with a shebang
    const { readFileSync } = require('fs');
    const content = readFileSync(scriptPath, 'utf-8') as string;
    expect(content).toMatch(/^#!\/bin\/bash/);
    // Must reference the configurable spec source (env var or project-relative)
    expect(content).toContain('OPENAPI_BASE');
    // Must NOT reference hardcoded user-specific paths
    expect(content).not.toContain('/home/ansible/');
    expect(content).not.toContain('/claudinno/');
  });
});
